# 標籤放在圓點左邊的縣市（北部、西部沿海擠在一起，放右邊會互相蓋到）
LABEL_LEFT = {"taipei", "taoyuan", "hsinchu-city", "miaoli", "taichung", "changhua", "yunlin",
              "chiayi-city", "tainan", "kaohsiung"}

# 離島小框：代號 → (中文, 框的左上角 x, y)
INSETS = {
    "lienchiang": ("連江", 12, 14),
    "kinmen": ("金門", 12, 78),
}
INSET_SIZE = (56, 48)


def project(lon, lat):
    return round((lon - LON0) * K * COS, 1), round((LAT0 - lat) * K, 1)


def _path(points):
    xy = [project(lon, lat) for lon, lat in points]
    return "M" + " L".join("%s,%s" % p for p in xy) + " Z"


def map_data():
    nodes = {key: {"name": name, "x": project(lon, lat)[0], "y": project(lon, lat)[1], "left": key in LABEL_LEFT}
             for key, (name, lon, lat) in CITIES.items()}
    w, h = INSET_SIZE
    for key, (name, x, y) in INSETS.items():
        nodes[key] = {"name": name, "x": x + w / 2, "y": y + h / 2 + 4, "inset": (x, y, w, h)}
    return {
        "width": WIDTH,
        "height": HEIGHT,
        "mainland": _path(MAINLAND),
        "islands": [_path(PENGHU)],
        "nodes": nodes,
    }
